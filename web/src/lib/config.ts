/**
 * 前端可调常量的唯一入口（架构 §8）。
 *
 * 为什么集中：PRD §10 的 10 项待确认问题全部按「建议默认值」落地，校方后续给出确切值时
 * 只改这一处即可，不必在业务代码里满仓库找魔法数字。**禁止在别处散落同类常量。**
 *
 * 本文件必须保持零依赖、零副作用：它被纯函数内核层引用，一旦碰 window/localStorage，
 * 整个内核层的可测性就塌了（架构 §7.1 一票否决项）。
 */

// ---------------------------------------------------------------------------
// 上下文截断（API-2 / Q1）
// ---------------------------------------------------------------------------

/** 上送 LLM 的历史最大轮数（1 轮 = 一次 user + 一次 assistant）。 */
export const CONTEXT_MAX_TURNS = 8;

/** 上送 LLM 的历史最大字符数。超限从最旧的整轮开始丢。 */
export const CONTEXT_MAX_CHARS = 6000;

// ---------------------------------------------------------------------------
// 本地历史留存（UX-7 / Q10）
// ---------------------------------------------------------------------------

/** localStorage 单场景会话最多保留的消息条数，超出自动裁剪最旧的完整轮次。 */
export const HISTORY_MAX_MESSAGES = 50;

// ---------------------------------------------------------------------------
// 重试策略（ERR-2 / Q7）
// ---------------------------------------------------------------------------

/** 单轮请求最多重试次数（不含首次尝试）。3 次尝试 = 1 首发 + 2 重试。 */
export const MAX_RETRY = 2;

/** 网络错误与 5xx 的退避基数（毫秒）。 */
export const RETRY_BASE_MS = 800;

/**
 * 429 且响应未带 Retry-After 时的退避基数（毫秒）。
 * 取 5s 而非 800ms：限流场景下抢着重试只会让服务端更堵（架构 §8 Q7）。
 */
export const RETRY_BASE_429_MS = 5000;

/** 退避抖动上限（毫秒）。报到日 5000 人同时在线，无抖动会造成重试尖峰同步。 */
export const RETRY_JITTER_MS = 300;

/**
 * 单次退避的硬上限（毫秒）。
 * 上游若返回 `Retry-After: 300` 这类超长值，自动重试仍按 30s 封顶，
 * 但 ClassifiedError.retryAfterSec 会保留真实值供 UI 倒计时展示，二者不冲突。
 */
export const RETRY_MAX_BACKOFF_MS = 30_000;

// ---------------------------------------------------------------------------
// 超时（ERR-1）
// ---------------------------------------------------------------------------

/** 首 token 超时（毫秒）。phase=sending 起计，到点即中止。 */
export const TTFB_TIMEOUT_MS = 15_000;

/** 流中空闲超时（毫秒）。每收到一个 token 重置；页面隐藏时必须暂停（风险 R2）。 */
export const IDLE_TIMEOUT_MS = 30_000;

// ---------------------------------------------------------------------------
// 兜底与埋点
// ---------------------------------------------------------------------------

/** 同会话连续终态失败达到该次数即展示人工兜底卡（UX-4）。 */
export const HANDOFF_FAILURE_THRESHOLD = 2;

/** 埋点上报端点（架构 A2）。 */
export const RUM_ENDPOINT = '/api/v1/rum';

/** 埋点队列达到该长度即触发一次 flush。 */
export const RUM_BATCH_SIZE = 10;

/** 埋点采样率，0~1。1 = 全量上报。 */
export const RUM_SAMPLE_RATE = 1;
